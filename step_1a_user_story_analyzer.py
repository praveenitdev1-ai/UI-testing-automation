def _analyze_ac_coverage(metadata: Dict[str, Any], config_file: Path) -> Dict[str, Any]:
    """Analyze acceptance criteria coverage based on extracted TSX fields."""
    
    with open(config_file, 'r', encoding='utf-8') as f:
        config = json.load(f)
    
    acceptance_criteria = config.get('acceptance_criteria', [])
    screen_layouts = config.get('screen_layouts', [])
    
    # Build map of story_id -> screen_name -> required fields
    story_fields = {}
    for layout in screen_layouts:
        story_id = layout.get('story_id', '')
        fields = []
        for section in layout.get('layout_sections', []):
            for field in section.get('fields', []):
                fields.append({
                    'id': field.get('id', ''),
                    'label': field.get('label', ''),
                    'type': field.get('type', ''),
                    'required': field.get('required', False)
                })
        story_fields[story_id] = {
            'screen_name': layout.get('screen_name', ''),
            'fields': fields
        }
    
    # Build map of extracted TSX fields by label (lowercase for matching)
    tsx_fields_by_label = {}
    tsx_fields_by_id = {}
    for screen in metadata.get('screens', []):
        for field in screen.get('fields', []):
            label = (field.get('label') or '').lower().strip()
            tsx_id = (field.get('tsx_id') or '').lower()
            if label:
                tsx_fields_by_label[label] = field
            if tsx_id:
                tsx_fields_by_id[tsx_id] = field
    
    # Group acceptance criteria by story
    ac_by_story = {}
    for ac in acceptance_criteria:
        story_id = ac.get('source_story_id', '')
        if story_id not in ac_by_story:
            ac_by_story[story_id] = []
        ac_by_story[story_id].append(ac)
    
    # Analyze coverage for each story
    coverage_result = {}
    
    for story_id, acs in ac_by_story.items():
        story_coverage = {}
        story_field_info = story_fields.get(story_id, {})
        required_fields = story_field_info.get('fields', [])
        
        for ac in acs:
            ac_id = ac.get('id', '')
            ac_title = ac.get('title', '')
            
            # Find fields mentioned in this AC's "then" clause
            then_text = ' '.join(ac.get('then', []))
            
            # Check which required fields are covered in TSX
            found_fields = []
            missing_fields = []
            
            for field in required_fields:
                field_label = field.get('label', '').lower().strip()
                field_id = field.get('id', '').lower()
                
                # Check if field exists in TSX (by label or id)
                found = (field_label in tsx_fields_by_label or 
                        field_id in tsx_fields_by_id or
                        any(field_label in k for k in tsx_fields_by_label.keys()))
                
                if found:
                    found_fields.append(field.get('label', field.get('id', '')))
                else:
                    missing_fields.append(field.get('label', field.get('id', '')))
            
            # Calculate coverage
            total_fields = len(required_fields)
            coverage_pct = round((len(found_fields) / total_fields * 100) if total_fields > 0 else 100)
            
            story_coverage[ac_id] = {
                'title': ac_title,
                'total_required_fields': total_fields,
                'found_in_tsx': len(found_fields),
                'missing_count': len(missing_fields),
                'coverage_percent': coverage_pct,
                'found_fields': found_fields,
                'missing_fields': missing_fields
            }
        
        if story_coverage:
            coverage_result[story_id] = story_coverage
    
    return coverage_result


if __name__ == '__main__':
    main()
